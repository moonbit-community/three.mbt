// Generates the WebGPU bindings of src/renderers/gpu from tools/gpu_spec.mjs:
//   gpu_types.mbt        opaque handle types and the union enums
//   gpu_descriptors.mbt  one struct per dictionary, with `new` / `default` / `reset` /
//                        `copy` / `to_js`
//   gpu_api.mbt          methods and properties
//   gpu_constants.mbt    GPUBufferUsage, GPUTextureUsage, GPUShaderStage, GPUMapMode,
//                        GPUColorWrite flags
// gpu_helpers.mbt (JS object builders, Promise glue, feature tests) is hand-written.
//
// Usage: node tools/gen_gpu_bindings.mjs [<repo>/src/renderers/gpu]
// then `moonfmt -w` the four files.

import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import {
	handles, interfaces, dictionaries, unions, namespaces, handleNames,
	parseMethod, parseProp, parseField, moonIdent,
} from './gpu_spec.mjs';

const here = path.dirname( url.fileURLToPath( import.meta.url ) );
const outDir = path.resolve( process.argv[ 2 ] ?? path.join( here, '..', 'src', 'renderers', 'gpu' ) );

const dictNames = new Set( Object.keys( dictionaries ) );
const unionNames = new Set( Object.keys( unions ) );
const HEADER = ( what ) => `// Generated by tools/gen_gpu_bindings.mjs from tools/gpu_spec.mjs: ${ what }.
// Do not edit by hand; change the spec and regenerate.\n\n`;

// MoonBit type of a parsed spec type.
function mbt( t ) {

	let s;
	if ( t.kind === 'array' ) s = `Array[${ mbt( t.elem ) }]`;
	else if ( t.kind === 'name' ) {

		s = { Int: 'Int', U32: 'Int', Double: 'Double', Bool: 'Bool', String: 'String', Unit: 'Unit',
			JsValue: '@core.JsValue', ArrayBuffer: '@core.ArrayBuffer' }[ t.name ] ?? t.name;

	} else throw new Error( 'no MoonBit type for ' + t.text );
	return t.nullable ? s + '?' : s;

}

const isPlain = ( t ) => t.kind === 'name' && ! t.nullable &&
	( [ 'Int', 'Double', 'Bool', 'String', 'JsValue', 'ArrayBuffer', 'Unit' ].includes( t.name ) || handleNames.has( t.name ) );

// MoonBit expression converting `e` (of type t, not optional) to @core.JsValue.
function toJs( e, t ) {

	if ( t.nullable ) {

		const inner = { ...t, nullable: false };
		return `gpu_nullable(${ e }, fn(v) { ${ toJs( 'v', inner ) } })`;

	}

	if ( t.kind === 'array' ) {

		if ( isPlain( t.elem ) ) return `gpu_array_of(${ e })`;
		return `gpu_array_map(${ e }, fn(x) { ${ toJs( 'x', t.elem ) } })`;

	}

	if ( t.name === 'JsValue' ) return e;
	if ( t.name === 'U32' ) return `gpu_u32(${ e })`;
	if ( t.name === 'Source' ) return `${ e }.to_buffer_source()`;
	if ( dictNames.has( t.name ) || unionNames.has( t.name ) ) return `${ e }.to_js()`;
	return `@core.JsValue::of(${ e })`;

}

// MoonBit expression converting the JsValue `e` to type t.
function fromJs( e, t ) {

	if ( t.nullable ) return `gpu_option(${ e })`;
	if ( t.kind === 'array' ) return `gpu_array_from(${ e })`;
	return `${ e }.cast()`;

}

const ffiName = ( kind, moon ) => `ffi_${ moonIdent( kind ) }_${ moon }`;
const recvName = ( kind ) => kind.replace( /^GPU/, '' ).replace( /^./, ( c ) => c.toLowerCase() ) || 'gpu';
const jsCall = ( js, n ) => {

	const ps = [ 'o', ...Array.from( { length: n }, ( _, i ) => 'a' + i ) ];
	return `(${ ps.join( ', ' ) }) => o.${ js }(${ ps.slice( 1 ).join( ', ' ) })`;

};

function emitMethod( kind, spec ) {

	const m = parseMethod( spec );
	const promise = m.ret.kind === 'promise';
	const ret = promise ? m.ret.elem : m.ret;
	const doc = `/// \`${ recvName( kind ) }.${ m.js }(${ m.params.length ? ' ' + m.params.map( ( p ) => p.name ).join( ', ' ) + ' ' : '' })\``;
	const generics = [];
	const externParams = [];
	const sigRequired = [];
	const sigOptional = [];
	const args = [];
	let wrap = promise || ! isPlain( ret );
	for ( const p of m.params ) {

		let ty = mbt( p.type );
		if ( p.type.kind === 'name' && p.type.name === 'Source' ) {

			ty = 'D' + generics.length;
			generics.push( `${ ty } : GPUBufferSource` );

		}

		if ( p.optional ) {

			wrap = true;
			externParams.push( `${ p.name } : @core.JsValue` );
			sigOptional.push( `${ p.name }? : ${ ty }` );
			args.push( `gpu_optional(${ p.name }, fn(v) { ${ toJs( 'v', p.type ) } })` );

		} else if ( isPlain( p.type ) ) {

			externParams.push( `${ p.name } : ${ ty }` );
			sigRequired.push( `${ p.name } : ${ ty }` );
			args.push( p.name );

		} else {

			wrap = true;
			externParams.push( `${ p.name } : @core.JsValue` );
			sigRequired.push( `${ p.name } : ${ ty }` );
			args.push( toJs( p.name, p.type ) );

		}

	}

	const self = `self : ${ kind }`;
	const body = jsCall( m.js, m.params.length );
	const extRet = promise || ! isPlain( ret ) ? '@core.JsValue' : mbt( ret );
	if ( ! wrap ) {

		return `///|\n${ doc }.\npub extern "js" fn ${ kind }::${ m.moon }(\n  ${ [ self, ...externParams ].join( ',\n  ' ) },\n) -> ${ mbt( ret ) } = "${ body }"\n`;

	}

	const ffi = ffiName( kind, m.moon );
	let out = `///|\nextern "js" fn ${ ffi }(\n  ${ [ `o : ${ kind }`, ...externParams ].join( ',\n  ' ) },\n) -> ${ extRet } = "${ body }"\n\n`;
	const g = generics.length ? `[${ generics.join( ', ' ) }]` : '';
	const call = `${ ffi }(${ [ 'self', ...args ].join( ', ' ) })`;
	if ( ! promise ) {

		const result = isPlain( ret ) ? call : fromJs( call, ret );
		out += `///|\n${ doc }.\npub fn${ g } ${ kind }::${ m.moon }(\n  ${ [ self, ...sigRequired, ...sigOptional ].join( ',\n  ' ) },\n) -> ${ mbt( ret ) } {\n  ${ result }\n}\n`;
		return out;

	}

	out += `///|\n${ doc }, as the JS Promise.\npub fn${ g } ${ kind }::${ m.moon }_promise(\n  ${ [ self, ...sigRequired, ...sigOptional ].join( ',\n  ' ) },\n) -> @core.JsValue {\n  ${ call }\n}\n\n`;
	const doneType = ret.kind === 'name' && ret.name === 'Unit' ? '() -> Unit' : `(${ mbt( ret ) }) -> Unit`;
	const done = ret.kind === 'name' && ret.name === 'Unit' ? 'fn(_) { on_done() }' : `fn(v) { on_done(${ fromJs( 'v', ret ) }) }`;
	const forward = [ ...m.params.filter( ( p ) => ! p.optional ).map( ( p ) => p.name ),
		...m.params.filter( ( p ) => p.optional ).map( ( p ) => `${ p.name }?=${ p.name }` ) ];
	out += `///|\n${ doc }: calls \`on_done\` with the result, \`on_error\` on rejection.\npub fn${ g } ${ kind }::${ m.moon }(\n  ${ [ self, ...sigRequired, `on_done : ${ doneType }`, ...sigOptional, 'on_error? : (@core.JsValue) -> Unit' ].join( ',\n  ' ) },\n) -> Unit {\n  gpu_then(self.${ m.moon }_promise(${ forward.join( ', ' ) }), ${ done }, on_error)\n}\n`;
	return out;

}

function emitProp( kind, spec ) {

	const p = parseProp( spec );
	const t = p.type;
	const doc = `/// \`${ recvName( kind ) }.${ p.js }\``;
	let out = '';
	if ( t.kind === 'fn' ) {

		out += `///|\n${ doc } = handler.\npub extern "js" fn ${ kind }::set_${ p.moon }(\n  self : ${ kind },\n  handler : (${ mbt( t.arg ) }) -> Unit,\n) -> Unit = "(o, f) => { o.${ p.js } = f; }"\n`;
		return out;

	}

	if ( t.kind === 'promise' ) {

		const ffi = ffiName( kind, p.moon );
		out += `///|\nextern "js" fn ${ ffi }(o : ${ kind }) -> @core.JsValue = "(o) => o.${ p.js }"\n\n`;
		out += `///|\n${ doc }, the JS Promise.\npub fn ${ kind }::${ p.moon }_promise(self : ${ kind }) -> @core.JsValue {\n  ${ ffi }(self)\n}\n\n`;
		out += `///|\n${ doc }: calls \`on_done\` when the Promise resolves.\npub fn ${ kind }::${ p.moon }(\n  self : ${ kind },\n  on_done : (${ mbt( t.elem ) }) -> Unit,\n  on_error? : (@core.JsValue) -> Unit,\n) -> Unit {\n  gpu_then(${ ffi }(self), fn(v) { on_done(${ fromJs( 'v', t.elem ) }) }, on_error)\n}\n`;
		return out;

	}

	if ( isPlain( t ) ) {

		out += `///|\n${ doc }.\npub extern "js" fn ${ kind }::${ p.moon }(self : ${ kind }) -> ${ mbt( t ) } = "(o) => o.${ p.js }"\n`;

	} else {

		const ffi = ffiName( kind, p.moon );
		out += `///|\nextern "js" fn ${ ffi }(o : ${ kind }) -> @core.JsValue = "(o) => o.${ p.js }"\n\n`;
		out += `///|\n${ doc }.\npub fn ${ kind }::${ p.moon }(self : ${ kind }) -> ${ mbt( t ) } {\n  ${ fromJs( `${ ffi }(self)`, t ) }\n}\n`;

	}

	if ( p.access === 'rw' ) {

		if ( ! isPlain( t ) ) throw new Error( 'rw needs a plain type: ' + spec );
		out += `\n///|\n${ doc } = value.\npub extern "js" fn ${ kind }::set_${ p.moon }(\n  self : ${ kind },\n  value : ${ mbt( t ) },\n) -> Unit = "(o, v) => { o.${ p.js } = v; }"\n`;

	}

	return out;

}

// JS initializer (upstream's class default) -> MoonBit expression of the field's type.
function initExpr( f ) {

	const t = f.type;
	const init = f.init;
	const some = ( e ) => ( f.optional ? `Some(${ e })` : e );
	if ( init === 'undefined' || init === 'null' ) {

		if ( ! f.optional ) throw new Error( `field ${ f.js } defaults to ${ init } but is not optional` );
		return 'None';

	}

	if ( /^'.*'$/.test( init ) ) return some( JSON.stringify( init.slice( 1, - 1 ) ) );
	if ( init === 'true' || init === 'false' ) return some( init );
	if ( init === '[]' ) return some( '[]' );
	if ( /^(0x[0-9A-Fa-f]+|-?\d+(\.\d+)?)$/.test( init ) ) {

		let n = Number( init );
		if ( t.name === 'U32' ) n = n | 0;
		if ( t.name === 'Double' ) return some( Number.isInteger( n ) ? n.toFixed( 1 ) : String( n ) );
		return some( String( n ) );

	}

	const cls = /^new (\w+)\(\)$/.exec( init );
	if ( cls ) return some( `${ cls[ 1 ] }::default()` );
	const obj = /^\{(.*)\}$/.exec( init );
	if ( obj ) {

		const kv = obj[ 1 ].trim() === '' ? [] : obj[ 1 ].split( ',' ).map( ( s ) => s.split( ':' ).map( ( x ) => x.trim() ) );
		return some( `${ t.name }::new(${ kv.map( ( [ k, v ] ) => `${ moonIdent( k ) }=${ v }` ).join( ', ' ) })` );

	}

	throw new Error( `cannot translate initializer ${ init } of ${ f.js }` );

}

function emitDictionary( name, d ) {

	const fields = d.fields.map( parseField );
	const where = d.cls ? `upstream class renderers/webgpu/descriptors/${ name === 'GPUMultisampleState' ? 'GPURenderPipelineDescriptor' : name }.js` : 'a WebGPU dictionary';
	let out = `///|\n/// \`${ name }\`, ${ where }.\npub(all) struct ${ name } {\n${ fields.map( ( f ) => `  mut ${ f.moon } : ${ mbt( f.type ) }${ f.optional ? '?' : '' }\n` ).join( '' ) }}\n\n`;
	// literal constructor
	const params = fields.map( ( f ) => f.optional ? `${ f.moon }? : ${ mbt( f.type ) }` : `${ f.moon }~ : ${ mbt( f.type ) }` );
	const lit = fields.length ? `{ ${ fields.map( ( f ) => f.moon ).join( ', ' ) } }` : `${ name }::{  }`;
	out += `///|\n/// An object literal: only the given optional fields become keys.\npub fn ${ name }::new(\n  ${ params.join( ',\n  ' ) }${ params.length ? ',' : '' }\n) -> ${ name } {\n  ${ lit }\n}\n\n`;
	if ( d.cls ) {

		out += `///|\n/// \`new ${ name }()\`: upstream's constructor defaults.\npub fn ${ name }::default() -> ${ name } {\n  { ${ fields.map( ( f ) => `${ f.moon }: ${ initExpr( f ) }` ).join( ', ' ) } }\n}\n\n`;
		const resets = fields.map( ( f ) => {

			const e = initExpr( f );
			if ( f.init === '[]' ) {

				return f.optional
					? `match self.${ f.moon } {\n    Some(a) => a.clear()\n    None => self.${ f.moon } = Some([])\n  }`
					: `self.${ f.moon }.clear()`;

			}

			return `self.${ f.moon } = ${ e }`;

		} );
		out += `///|\n/// \`reset()\`: back to the constructor defaults (arrays are emptied in place).\npub fn ${ name }::reset(self : ${ name }) -> Unit {\n  ${ resets.join( '\n  ' ) }\n}\n\n`;
		out += `///|\n/// \`Object.assign( {}, descriptor )\`: a shallow copy.\npub fn ${ name }::copy(self : ${ name }) -> ${ name } {\n  { ${ fields.map( ( f ) => `${ f.moon }: self.${ f.moon }` ).join( ', ' ) } }\n}\n\n`;

	}

	const sets = fields.map( ( f ) => f.optional
		? `match self.${ f.moon } {\n    Some(v) => gpu_set(o, "${ f.js }", ${ toJs( 'v', f.type ) })\n    None => ()\n  }`
		: `gpu_set(o, "${ f.js }", ${ toJs( `self.${ f.moon }`, f.type ) })` );
	out += `///|\n/// A fresh JS object with the present fields, in field order.\npub fn ${ name }::to_js(self : ${ name }) -> @core.JsValue {\n  ${ fields.length ? '' : 'ignore(self)\n  ' }let o = gpu_object()\n  ${ sets.join( '\n  ' ) }${ sets.length ? '\n  ' : '' }o\n}\n\n`;
	return out;

}

function emitUnion( name, variants ) {

	let out = `///|\n/// A union-typed member (\`${ variants.map( ( [ , t ] ) => t.replace( /"/g, '\'' ) ).join( ' | ' ) }\`).\npub(all) enum ${ name } {\n`;
	for ( const [ v, t ] of variants ) out += t.startsWith( '"' ) ? `  ${ v }\n` : `  ${ v }(${ t })\n`;
	out += `}\n\n///|\n/// The JS value passed to WebGPU.\npub fn ${ name }::to_js(self : ${ name }) -> @core.JsValue {\n  match self {\n`;
	for ( const [ v, t ] of variants ) {

		if ( t.startsWith( '"' ) ) out += `    ${ v } => @core.JsValue::of(${ t })\n`;
		else out += `    ${ v }(v) => ${ toJs( 'v', { kind: 'name', name: t, nullable: false } ) }\n`;

	}

	out += '  }\n}\n\n';
	return out;

}

// gpu_types.mbt
{

	let out = HEADER( 'the opaque WebGPU object types and the union-typed members' );
	out += `// Handles are opaque JS objects. Where WebGPU returns \`null\` or \`undefined\` the binding
// returns \`T?\`; Option of an external type is boxed, so compare optional handles with
// \`same_handle\`, never \`physical_equal\`.\n\n`;
	for ( const [ h, doc ] of handles ) out += `///|\n/// ${ doc }\n#external\npub type ${ h }\n\n`;
	for ( const [ n, v ] of Object.entries( unions ) ) out += emitUnion( n, v );
	fs.writeFileSync( path.join( outDir, 'gpu_types.mbt' ), out.trimEnd() + '\n' );

}

// gpu_descriptors.mbt
{

	let out = HEADER( 'the dictionaries (descriptors) passed to WebGPU' );
	out += `// One struct per dictionary, fields in upstream's key order. A field is an Option when the
// key can be absent: \`None\` leaves the key out of the object \`to_js\` builds, so the JS
// object has exactly the keys upstream's has, in the same order. The reusable descriptor
// classes of renderers/webgpu/descriptors are mirrored with \`X::default()\` (the
// constructor), \`reset()\` and \`copy()\`; every dictionary has \`X::new(...)\`, which reads like
// an object literal.\n\n`;
	for ( const [ n, d ] of Object.entries( dictionaries ) ) out += emitDictionary( n, d );
	fs.writeFileSync( path.join( outDir, 'gpu_descriptors.mbt' ), out.trimEnd() + '\n' );

}

// gpu_api.mbt
let methodCount = 0, propCount = 0;
{

	let out = HEADER( 'WebGPU methods and properties' );
	out += `// \`x.fooBar( ... )\` is \`x.foo_bar( ... )\`. Optional IDL parameters are labelled optional
// arguments (\`None\` passes \`undefined\`). Promise-returning methods take \`on_done\` (and an
// optional \`on_error\`) and have a \`_promise\` twin returning the raw JS Promise.\n\n`;
	for ( const [ kind, { methods, props } ] of Object.entries( interfaces ) ) {

		if ( methods.length + props.length === 0 ) continue;
		out += `// ${ kind }\n\n`;
		for ( const m of methods ) { out += emitMethod( kind, m ) + '\n'; methodCount ++; }
		for ( const p of props ) { out += emitProp( kind, p ) + '\n'; propCount ++; }

	}

	fs.writeFileSync( path.join( outDir, 'gpu_api.mbt' ), out.trimEnd() + '\n' );

}

// gpu_constants.mbt
let constCount = 0;
{

	let out = HEADER( 'the WebGPU flag namespaces' );
	out += `// \`GPUBufferUsage.COPY_DST\` is \`GPU_BUFFER_USAGE_COPY_DST\`. The WebGPU specification fixes
// the values, so they are constants rather than reads of the globals (feature tests such
// as \`GPUTextureUsage.TRANSIENT_ATTACHMENT !== undefined\` are in gpu_helpers.mbt).\n\n`;
	for ( const [ ns, values ] of Object.entries( namespaces ) ) {

		const prefix = 'GPU_' + moonIdent( ns.replace( /^GPU/, '' ) ).toUpperCase();
		for ( const [ k, v ] of Object.entries( values ) ) {

			out += `///|\npub const ${ prefix }_${ k } : Int = 0x${ v.toString( 16 ).toUpperCase().padStart( 4, '0' ) }\n\n`;
			constCount ++;

		}

	}

	fs.writeFileSync( path.join( outDir, 'gpu_constants.mbt' ), out.trimEnd() + '\n' );

}

console.log( `wrote ${ handles.length } types, ${ Object.keys( unions ).length } unions, ${ Object.keys( dictionaries ).length } dictionaries, ${ methodCount } methods, ${ propCount } properties, ${ constCount } constants to ${ outDir }` );
