#!/usr/bin/env node
// Generates src/nodes/tsl_swizzle.mbt: the swizzle members TSLCore.js puts on
// `Node.prototype` for every 1-4 component combination of `xyzw` and its `rgba` and
// `stpq` aliases (340 properties, 3 spellings each):
//
//   node.xyz        -> n.xyz()          a cached SplitNode (`Node::swizzle`)
//   node.setXYZ( v ) -> n.set_xyz(v)    a SetNode (`Node::set_swizzle`)
//   node.flipXYZ()  -> n.flip_xyz()     a FlipNode (`Node::flip_swizzle`)
//
// Every spelling passes the `xyzw` property, as upstream's `setProtoSwizzle` does, so
// `rgb` and `xyz` share one cached SplitNode. The script checks the generated names
// against MoonBit keywords and against the `Node` methods defined elsewhere in
// src/nodes, plus the chained TSL methods upstream adds (`addMethodChaining`), and
// fails on a clash. Run `moonfmt -w src/nodes/tsl_swizzle.mbt` afterwards.
//
//   node tools/gen_swizzle.mjs [path/to/three.js]

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve( path.dirname( fileURLToPath( import.meta.url ) ), '..' );
const upstream = path.resolve( process.argv[ 2 ] || path.join( repoRoot, '.repos/three.js' ) );
const nodesDir = path.join( repoRoot, 'src/nodes' );
const outFile = path.join( nodesDir, 'tsl_swizzle.mbt' );

// MoonBit keywords and reserved words (identifiers that cannot name a method).
const KEYWORDS = new Set( [
	'as', 'else', 'extern', 'fn', 'fnalias', 'if', 'let', 'const', 'match', 'using', 'mut',
	'type', 'typealias', 'struct', 'enum', 'trait', 'traitalias', 'derive', 'while', 'break',
	'continue', 'import', 'return', 'throw', 'raise', 'try', 'catch', 'pub', 'priv',
	'readonly', 'true', 'false', '_', 'test', 'loop', 'for', 'in', 'impl', 'with', 'guard',
	'async', 'is', 'suberror', 'and', 'letrec', 'enumview', 'noraise', 'defer', 'lexmark',
	'module', 'move', 'ref', 'static', 'super', 'unsafe', 'use', 'where', 'await', 'dyn',
	'abstract', 'do', 'final', 'macro', 'override', 'typeof', 'virtual', 'yield', 'local',
	'method', 'alias', 'assert', 'package', 'recur', 'sealed', 'include', 'not', 'self',
] );

const swizzleA = [ 'x', 'y', 'z', 'w' ];
const swizzleB = [ 'r', 'g', 'b', 'a' ];
const swizzleC = [ 's', 't', 'p', 'q' ];

// Upstream's loop order: a, ab, abc, abcd, ... for each first component.
const properties = [];

for ( let a = 0; a < 4; a ++ ) {

	properties.push( [ a ] );

	for ( let b = 0; b < 4; b ++ ) {

		properties.push( [ a, b ] );

		for ( let c = 0; c < 4; c ++ ) {

			properties.push( [ a, b, c ] );

			for ( let d = 0; d < 4; d ++ ) properties.push( [ a, b, c, d ] );

		}

	}

}

const spell = ( indices, set ) => indices.map( ( i ) => set[ i ] ).join( '' );

// Node methods defined by hand in src/nodes (`fn Node::name`).
const existing = new Map();

for ( const file of fs.readdirSync( nodesDir ) ) {

	if ( ! file.endsWith( '.mbt' ) || file === 'tsl_swizzle.mbt' || file.endsWith( '.mbti' ) ) continue;

	const text = fs.readFileSync( path.join( nodesDir, file ), 'utf8' );

	for ( const m of text.matchAll( /fn\s+Node::([a-z_][a-z0-9_]*)/g ) ) existing.set( m[ 1 ], file );

}

// Chained TSL methods upstream adds to Node.prototype, snake-cased, with their
// `Assign` forms.
const snakeCase = ( name ) => name.replace( /[A-Z]/g, ( c ) => '_' + c.toLowerCase() );
const chained = new Map();

function walk( dir ) {

	for ( const entry of fs.readdirSync( dir, { withFileTypes: true } ) ) {

		const full = path.join( dir, entry.name );

		if ( entry.isDirectory() ) walk( full );
		else if ( entry.name.endsWith( '.js' ) ) {

			const text = fs.readFileSync( full, 'utf8' );

			for ( const m of text.matchAll( /addMethodChaining\(\s*'(\w+)'/g ) ) {

				const rel = path.relative( upstream, full );
				chained.set( snakeCase( m[ 1 ] ), rel );
				if ( m[ 1 ] !== 'assign' ) chained.set( snakeCase( m[ 1 ] + 'Assign' ), rel );

			}

		}

	}

}

const nodesSrc = path.join( upstream, 'src/nodes' );
if ( fs.existsSync( nodesSrc ) ) walk( nodesSrc );
else console.warn( `gen_swizzle: ${ nodesSrc } not found; chained names not checked` );

const clashes = [];
const generated = new Set();

function check( name ) {

	if ( generated.has( name ) ) clashes.push( `${ name }: generated twice` );
	generated.add( name );
	if ( KEYWORDS.has( name ) ) clashes.push( `${ name }: MoonBit keyword` );
	if ( existing.has( name ) ) clashes.push( `${ name }: Node method in ${ existing.get( name ) }` );
	if ( chained.has( name ) ) clashes.push( `${ name }: chained TSL method of ${ chained.get( name ) }` );

}

const out = [];

out.push( '// Generated by tools/gen_swizzle.mjs from TSLCore.js `setProtoSwizzle`; do not edit.' );
out.push( '// Each spelling (`xyzw`, `rgba`, `stpq`) passes the `xyzw` property.' );

for ( const indices of properties ) {

	const property = spell( indices, swizzleA );

	for ( const set of [ swizzleA, swizzleB, swizzleC ] ) {

		const name = spell( indices, set );
		check( name );
		out.push( '', '///|', `pub fn Node::${ name }(self : Node) -> Node {`, `  self.swizzle("${ property }")`, '}' );

	}

}

for ( const indices of properties ) {

	const property = spell( indices, swizzleA );

	for ( const set of [ swizzleA, swizzleB, swizzleC ] ) {

		const name = 'set_' + spell( indices, set );
		check( name );
		out.push( '', '///|', `pub fn Node::${ name }(self : Node, value : &IntoTsl) -> Node {`, `  self.set_swizzle("${ property }", value)`, '}' );

	}

}

for ( const indices of properties ) {

	const property = spell( indices, swizzleA );

	for ( const set of [ swizzleA, swizzleB, swizzleC ] ) {

		const name = 'flip_' + spell( indices, set );
		check( name );
		out.push( '', '///|', `pub fn Node::${ name }(self : Node) -> Node {`, `  self.flip_swizzle("${ property }")`, '}' );

	}

}

if ( clashes.length > 0 ) {

	console.error( 'gen_swizzle: name clashes:\n  ' + clashes.join( '\n  ' ) );
	process.exit( 1 );

}

fs.writeFileSync( outFile, out.join( '\n' ) + '\n' );
console.log( `gen_swizzle: wrote ${ path.relative( repoRoot, outFile ) } (${ generated.size } methods, ${ properties.length } properties; checked against ${ existing.size } Node methods and ${ chained.size } chained names)` );
