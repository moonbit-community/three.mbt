#!/usr/bin/env node
// Regenerates the GLSL and data tables of src/renderers/shaders from upstream.
//
//   node tools/gen_shaders.mjs [path/to/three.js]
//
// The upstream path defaults to .repos/three.js. Strings come from the evaluated
// upstream modules, not from their source text, so template-literal interpolation
// and escapes are already resolved here. The source text is only audited, to list
// which files use either. Hand-written files (shader_lib.mbt, uniforms_lib.mbt,
// dfg_lut_data.mbt) are not touched.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = path.resolve( path.dirname( fileURLToPath( import.meta.url ) ), '..' );
const outDir = path.join( repoRoot, 'src/renderers/shaders' );

// ShaderChunk/ files that upstream leaves out of the ShaderChunk object. `core`
// exports them as `default_vertex` and `default_fragment` for ShaderMaterial.
const UNKEYED_CHUNKS = new Set( [ 'default_vertex', 'default_fragment' ] );

// ShaderLib/ files that upstream leaves out of the ShaderChunk object. These
// become public lets, because WebGLShadowMap imports the module directly.
const UNKEYED_LIBS = new Set( [ 'vsm' ] );

function snakeCase( name ) {

	return name.replace( /[A-Z]/g, ( c ) => '_' + c.toLowerCase() );

}

function chunkIdent( key ) {

	return 'chunk_' + snakeCase( key );

}

// Lines of a `#|` string join with "\n" and have no terminator, so a string maps to
// its split('\n') one to one. `#|` is raw: backslashes, `\{` and `$` need no escaping.
// Anything else the lexer could treat as a line break or reject is refused here,
// rather than being emitted wrongly. So is a space or tab at the very end of the
// string: moonfmt keeps them on inner `#|` lines but strips them from the last one.
export function mbtStringLines( text ) {

	const bad = text.match( /[\u0000-\u0008\u000b-\u001f\u007f]/ );
	if ( bad !== null ) throw new Error( `control character U+${ bad[ 0 ].charCodeAt( 0 ).toString( 16 ) } cannot appear in a #| string` );
	if ( ! text.isWellFormed() ) throw new Error( 'lone surrogate cannot appear in a #| string' );
	if ( /[ \t]$/.test( text ) ) throw new Error( 'moonfmt would strip the space or tab at the end of this string' );

	return text.split( '\n' ).map( ( line ) => `  #|${ line }` ).join( '\n' );

}

export function mbtStringLet( ident, text, isPublic = false, doc = null ) {

	const docLine = doc === null ? '' : `/// ${ doc }\n`;
	return `///|\n${ docLine }${ isPublic ? 'pub ' : '' }let ${ ident } : String =\n${ mbtStringLines( text ) }\n`;

}

function header( source ) {

	return `// Generated by tools/gen_shaders.mjs from upstream\n// ${ source }. Do not edit.\n\n`;

}

function auditSource( file, audit ) {

	const body = fs.readFileSync( file, 'utf8' )
		.replace( /^export (default|const \w+ =) \/\* glsl \*\/`/gm, '' )
		.replace( /^`;$/gm, '' );

	if ( body.includes( '`' ) ) audit.other.push( file );
	if ( body.includes( '${' ) ) audit.interpolated.push( file );
	if ( body.includes( '\\' ) ) audit.escaped.push( file );

}

function listGlsl( dir ) {

	return fs.readdirSync( dir ).filter( ( f ) => f.endsWith( '.glsl.js' ) ).sort();

}

export async function main( upstream ) {

	const shaders = path.join( upstream, 'src/renderers/shaders' );
	const load = ( rel ) => import( pathToFileURL( path.join( shaders, rel ) ).href );
	const { ShaderChunk } = await load( 'ShaderChunk.js' );
	const { getDFGLUT } = await load( 'DFGLUTData.js' );

	const written = [];
	const write = ( name, text ) => {

		const file = path.join( outDir, name );
		fs.writeFileSync( file, text );
		written.push( file );

	};

	const audit = { interpolated: [], escaped: [], other: [] };
	const pending = new Set( Object.keys( ShaderChunk ) );
	const take = ( key, value ) => {

		if ( ! pending.delete( key ) ) throw new Error( `${ key } is not an upstream ShaderChunk key` );
		if ( ShaderChunk[ key ] !== value ) throw new Error( `${ key } differs from its module` );

	};

	fs.mkdirSync( outDir, { recursive: true } );
	for ( const f of fs.readdirSync( outDir ) ) {

		if ( /^(chunk|lib)_.*\.mbt$/.test( f ) ) fs.rmSync( path.join( outDir, f ) );

	}

	for ( const f of listGlsl( path.join( shaders, 'ShaderChunk' ) ) ) {

		const name = f.slice( 0, - '.glsl.js'.length );
		auditSource( path.join( shaders, 'ShaderChunk', f ), audit );
		if ( UNKEYED_CHUNKS.has( name ) ) continue;

		const module = await load( `ShaderChunk/${ f }` );
		take( name, module.default );
		write(
			`chunk_${ name }.mbt`,
			header( `src/renderers/shaders/ShaderChunk/${ f }` ) + mbtStringLet( chunkIdent( name ), module.default )
		);

	}

	for ( const f of listGlsl( path.join( shaders, 'ShaderLib' ) ) ) {

		const name = f.slice( 0, - '.glsl.js'.length );
		auditSource( path.join( shaders, 'ShaderLib', f ), audit );

		const module = await load( `ShaderLib/${ f }` );
		const exportNames = Object.keys( module ).sort().join();
		if ( exportNames !== 'fragment,vertex' ) throw new Error( `${ f } exports ${ exportNames }` );

		let body;
		if ( UNKEYED_LIBS.has( name ) ) {

			body = mbtStringLet( `${ name }_vertex`, module.vertex, true, `Upstream \`${ name }.vertex\`.` ) + '\n' +
				mbtStringLet( `${ name }_fragment`, module.fragment, true, `Upstream \`${ name }.fragment\`.` );

		} else {

			take( `${ name }_vert`, module.vertex );
			take( `${ name }_frag`, module.fragment );
			body = mbtStringLet( chunkIdent( `${ name }_vert` ), module.vertex ) + '\n' +
				mbtStringLet( chunkIdent( `${ name }_frag` ), module.fragment );

		}

		write( `lib_${ snakeCase( name ) }.mbt`, header( `src/renderers/shaders/ShaderLib/${ f }` ) + body );

	}

	if ( pending.size !== 0 ) throw new Error( `no module for: ${ [ ...pending ].join( ', ' ) }` );

	const entries = Object.keys( ShaderChunk )
		.map( ( key ) => `  (${ JSON.stringify( key ) }, ${ chunkIdent( key ) }),` )
		.join( '\n' );

	write( 'shader_chunk.mbt', header( 'src/renderers/shaders/ShaderChunk.js' ) +
		'///|\n' +
		'/// Upstream `ShaderChunk`, in upstream key order. Resolves `#include <x>`.\n' +
		`pub let shader_chunk : Map[String, String] = Map([\n${ entries }\n])\n` );

	const data = Array.from( getDFGLUT().image.data );
	const rows = [];
	for ( let i = 0; i < data.length; i += 8 ) {

		rows.push( '  ' + data.slice( i, i + 8 ).map( ( v ) => '0x' + v.toString( 16 ).padStart( 4, '0' ) ).join( ', ' ) + ',' );

	}

	write( 'dfg_lut_table.mbt', header( 'the DATA table of src/renderers/shaders/DFGLUTData.js' ) +
		`///|\nlet dfg_lut_table : Array[Int] = [\n${ rows.join( '\n' ) }\n]\n` );

	for ( const file of written ) execFileSync( 'moonfmt', [ '-w', file ] );

	const rel = ( list ) => list.map( ( f ) => path.relative( shaders, f ) );
	console.log( `wrote ${ written.length } files to ${ path.relative( repoRoot, outDir ) }` );
	console.log( `ShaderChunk keys: ${ Object.keys( ShaderChunk ).length }` );
	console.log( 'source files with ${...}:', rel( audit.interpolated ) );
	console.log( 'source files with a backslash:', rel( audit.escaped ) );
	console.log( 'source files with a nested backtick:', rel( audit.other ) );

}

if ( process.argv[ 1 ] !== undefined && import.meta.url === pathToFileURL( process.argv[ 1 ] ).href ) {

	await main( path.resolve( process.argv[ 2 ] ?? path.join( repoRoot, '.repos/three.js' ) ) );

}
