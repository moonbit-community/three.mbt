// Generates src/renderers/webgl_fallback/nodes_glsl_node_builder_tables.mbt from upstream
// GLSLNodeBuilder.js: the polyfill sources, defaultPrecisions and the reserved keywords,
// byte for byte (then moonfmt).
//
//   node tools/gen_glsl_tables.mjs [--check] [path/to/three.js]
//   (default: $THREE_UPSTREAM or .repos/three.js; --check: write nothing, exit 1 if stale)
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve( path.dirname( fileURLToPath( import.meta.url ) ), '..' );
const args = process.argv.slice( 2 );
const upstream = path.resolve( repo, args.find( ( a ) => ! a.startsWith( '--' ) ) ?? process.env.THREE_UPSTREAM ?? '.repos/three.js' );
const outFile = path.join( repo, 'src/renderers/webgl_fallback/nodes_glsl_node_builder_tables.mbt' );
const src = fs.readFileSync( path.join( upstream, 'src/renderers/webgl-fallback/nodes/GLSLNodeBuilder.js' ), 'utf8' );
const lit = ( s ) => JSON.stringify( s );
let out = `// Generated by tools/gen_glsl_tables.mjs from upstream GLSLNodeBuilder.js: the
// \`glslPolyfills\` sources, \`defaultPrecisions\` and \`glslReservedKeywords\`, byte for
// byte. Do not edit by hand.

///|
/// \`glslPolyfills\`: name -> GLSL source of its \`CodeNode\`, in upstream's key order.
let _glsl_polyfill_sources : Array[(String, String)] = [
`;
const re = /(\w+): new CodeNode\( \/\* glsl \*\/(`[^`]*`|'[^']*') \)/g;
let m;
while ( ( m = re.exec( src ) ) ) out += `  (${lit( m[ 1 ] )}, ${lit( eval( m[ 2 ] ) )}),\n`;
out += `]\n\n`;
const prec = /const defaultPrecisions = (`[^`]*`);/.exec( src )[ 1 ];
out += `///|\n/// \`defaultPrecisions\`.\nlet _glsl_default_precisions : String = ${lit( eval( prec ) )}\n\n`;
const kw = /const glslReservedKeywords = new Set\( (\[[\s\S]*?\]) \);/.exec( src )[ 1 ];
const words = eval( kw );
out += `///|\n/// \`glslReservedKeywords\`.\nlet _glsl_reserved_keyword_list : Array[String] = [\n`;
for ( let i = 0; i < words.length; i += 8 ) out += '  ' + words.slice( i, i + 8 ).map( lit ).join( ', ' ) + ',\n';
out += `]\n`;
// The committed file is formatted by moonfmt.
const tmp = fs.mkdtempSync( path.join( os.tmpdir(), 'gen_glsl_tables-' ) );
const tmpFile = path.join( tmp, 'tables.mbt' );
fs.writeFileSync( tmpFile, out );
const fmt = spawnSync( 'moonfmt', [ '-w', tmpFile ], { encoding: 'utf8' } );
if ( fmt.status !== 0 ) throw new Error( 'moonfmt failed: ' + fmt.stderr );
out = fs.readFileSync( tmpFile, 'utf8' );
fs.rmSync( tmp, { recursive: true, force: true } );
const rel = path.relative( repo, outFile );
if ( args.includes( '--check' ) ) {

	const ok = fs.existsSync( outFile ) && fs.readFileSync( outFile, 'utf8' ) === out;
	console.log( ok ? `${rel} is up to date` : `${rel} is stale (run node tools/gen_glsl_tables.mjs)` );
	process.exit( ok ? 0 : 1 );

}

fs.writeFileSync( outFile, out );
console.log( 'wrote', rel, words.length, 'keywords' );
