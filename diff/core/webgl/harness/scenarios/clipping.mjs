export async function run({ src, createMockGL }) {
  const T = await import(src + '/Three.Core.js');
  const { WebGLProperties } = await import(src + '/renderers/webgl/WebGLProperties.js');
  const { WebGLClipping } = await import(src + '/renderers/webgl/WebGLClipping.js');
  const gl = createMockGL({});
  const clipping = new WebGLClipping(new WebGLProperties());
  const camera = new T.PerspectiveCamera(50, 1, 0.1, 100);
  camera.position.set(1, 2, 3);
  camera.lookAt(0, 0, 0);
  camera.updateMatrixWorld();
  const p1 = new T.Plane(new T.Vector3(1, 0, 0), 1);
  const p2 = new T.Plane(new T.Vector3(0, 1, 0), - 2);
  const p3 = new T.Plane(new T.Vector3(0, 0.6, 0.8), 0.5);
  const state = (label) => gl.__note(label, [clipping.uniform.value, clipping.uniform.needsUpdate, clipping.numPlanes, clipping.numIntersection]);
  gl.__note('init', clipping.init([p1], true));
  clipping.setGlobalState([p1], camera);
  state('global');
  const material = new T.MeshBasicMaterial();
  material.clippingPlanes = [p2, p3];
  material.clipIntersection = true;
  clipping.setState(material, camera, false);
  state('local');
  clipping.setState(material, camera, true);
  state('local cached');
  const m2 = new T.MeshBasicMaterial();
  clipping.setState(m2, camera, false);
  state('none');
  clipping.beginShadows();
  state('shadows');
  clipping.setState(material, camera, false);
  state('shadows no clip');
  material.clipShadows = true;
  clipping.setState(material, camera, false);
  state('shadows clip');
  clipping.endShadows();
  gl.__note('init', clipping.init([], false));
  gl.__note('init', clipping.init([], false));
  clipping.setState(material, camera, false);
  state('disabled');
  return gl.__log;
}
