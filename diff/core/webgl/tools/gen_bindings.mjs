// Generates src/renderers/webgl/gl_context.mbt and gl_constants.mbt from gl_spec.mjs.
// Usage: node gen_bindings.mjs <repo>/src/renderers/webgl
import fs from 'node:fs';
import path from 'node:path';
import { methods, extensionMethods, handles, constants } from './gl_spec.mjs';
import { parse } from './gen_bindings_lib.mjs';

const outDir = process.argv[2];
if (!outDir) throw new Error('usage: node gen_bindings.mjs <out dir>');


const handleNames = new Set(handles.map(([h]) => h));

function mbtType(t) {
  if (t === 'JsValue') return '@core.JsValue';
  if (t.endsWith('?')) return t;
  return t;
}

function emit(recv, recvType, spec) {
  const { js, moon, params, ret } = parse(spec);
  let generic = [];
  let needsWrapper = false;
  const externParams = [];
  const wrapperParams = [];
  const args = [];
  for (const p of params) {
    if (p.type === 'Data') {
      const tv = 'D' + generic.length;
      generic.push(`${tv} : GLData`);
      needsWrapper = true;
      externParams.push(`${p.name} : @core.JsValue`);
      wrapperParams.push(`${p.name} : ${tv}`);
      args.push(`${p.name}.to_gl_data()`);
    } else if (p.type === 'Array[Int]') {
      needsWrapper = true;
      externParams.push(`${p.name} : FixedArray[Int]`);
      wrapperParams.push(`${p.name} : Array[Int]`);
      args.push(`FixedArray::from_array(${p.name}[:])`);
    } else if (p.type.endsWith('?')) {
      needsWrapper = true;
      externParams.push(`${p.name} : @core.JsValue`);
      wrapperParams.push(`${p.name} : ${p.type}`);
      args.push(`gl_nullable(${p.name})`);
    } else {
      externParams.push(`${p.name} : ${mbtType(p.type)}`);
      wrapperParams.push(`${p.name} : ${mbtType(p.type)}`);
      args.push(p.name);
    }
  }
  let externRet = mbtType(ret);
  let wrapRet = mbtType(ret);
  let convert = (e) => e;
  if (ret.endsWith('?')) {
    needsWrapper = true;
    externRet = '@core.JsValue';
    convert = (e) => `gl_option(${e})`;
  }
  const jsParams = ['o', ...params.map((_, i) => 'a' + i)];
  const jsBody = `(${jsParams.join(', ')}) => o.${js}(${params.map((_, i) => 'a' + i).join(', ')})`;
  const doc = `/// \`${recv}.${js}( ${params.map((p) => p.name).join(', ')} )\`.`;
  const self = `self : ${recvType}`;
  if (!needsWrapper) {
    return `///|\n${doc}\npub extern "js" fn ${recvType}::${moon}(\n  ${[self, ...externParams].join(',\n  ')},\n) -> ${externRet} = "${jsBody}"\n`;
  }
  const ffi = `ffi_${recvType === 'WebGL2RenderingContext' ? 'gl' : 'ext'}_${moon}`;
  const g = generic.length ? `[${generic.join(', ')}]` : '';
  return `///|\nextern "js" fn ${ffi}(\n  ${[`${recv} : ${recvType}`, ...externParams].join(',\n  ')},\n) -> ${externRet} = "${jsBody}"\n\n` +
    `///|\n${doc}\npub fn${g} ${recvType}::${moon}(\n  ${[self, ...wrapperParams].join(',\n  ')},\n) -> ${wrapRet} {\n  ${convert(`${ffi}(${['self', ...args].join(', ')})`)}\n}\n`;
}

let out = `// Generated by gen_bindings.mjs from gl_spec.mjs (diff/core/webgl harness). Do not edit
// by hand: add the call to the spec and regenerate. One method per \`gl.*\` call that the
// upstream renderer makes; names are \`camelCase\` -> \`snake_case\` with \`2D\`/\`3D\` kept
// attached (\`texImage2D\` -> \`tex_image2d\`). Second overloads have their own names.\n\n`;
for (const s of methods) out += emit('gl', 'WebGL2RenderingContext', s) + '\n';
out += `// Extension objects. Constants on them (\`ext.COMPRESSED_RGB_S3TC_DXT1_EXT\`) are read\n// with \`GLExtension::constant\`.\n\n`;
for (const s of extensionMethods) out += emit('extension', 'GLExtension', s) + '\n';
fs.writeFileSync(path.join(outDir, 'gl_context.mbt'), out.trimEnd() + '\n');

let c = `// Generated by gen_bindings.mjs from gl_spec.mjs. WebGL 2 constants, \`gl.FOO\` -> \`GL_FOO\`.\n// Values are fixed by the WebGL 2 specification, so they are compile-time constants\n// rather than reads from the context.\n\n`;
for (const [k, v] of Object.entries(constants).sort()) {
  c += `///|\npub const GL_${k} : Int = 0x${v.toString(16).toUpperCase().padStart(4, '0')}\n\n`;
}
fs.writeFileSync(path.join(outDir, 'gl_constants.mbt'), c.trimEnd() + '\n');
console.log(`wrote ${methods.length} context methods, ${extensionMethods.length} extension methods, ${Object.keys(constants).length} constants`);
