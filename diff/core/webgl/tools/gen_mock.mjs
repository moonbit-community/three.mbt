// Writes harness/mock_gl.cjs (constants from gl_spec.mjs + mock_gl_body.js) and embeds the
// same source into <repo>/src/renderers/webgl/webgl_mock_gl_test.mbt.
// Usage: node tools/gen_mock.mjs [--check] [<repo>]   (<repo> defaults to this repository;
//   --check writes nothing and exits 1 if either file is stale)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { constants, methods } from './gl_spec.mjs';
import { parse } from './gen_bindings_lib.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const cli = process.argv.slice(2);
const check = cli.includes('--check');
const repo = cli.find((a) => !a.startsWith('--')) ?? path.resolve(here, '../../../..');
const outputs = [];
const body = fs.readFileSync(path.join(here, '..', 'harness', 'mock_gl_body.js'), 'utf8');
const jsNames = [...new Set(methods.map((m) => parse(m).js))].sort();
const source = `const MOCK_GL_CONSTANTS = ${JSON.stringify(constants)};\nconst MOCK_GL_METHODS = ${JSON.stringify(jsNames)};\n${body}`;
outputs.push([path.join(here, '..', 'harness', 'mock_gl.cjs'),
  `// Generated by tools/gen_mock.mjs from mock_gl_body.js and gl_spec.mjs. Do not edit.\n${source}\nmodule.exports = { createMockGL, createMockAnimationContext };\n`]);
{
  const lines = `(options) => {\n${source}\nreturn { createMockGL, createMockAnimationContext };\n}`.split('\n').map((l) => '  #|' + l).join('\n');
  const mbt = `// Generated by diff/core/webgl/tools/gen_mock.mjs from mock_gl_body.js: the
// recording mock WebGL 2 context the differential tests use. Do not edit by hand.

///|
extern "js" fn ffi_mock_gl_module(options : Unit) -> @core.JsValue =
${lines}
`;
  outputs.push([path.join(repo, 'src/renderers/webgl/webgl_mock_gl_test.mbt'), mbt]);
}
if (check) {
  const stale = outputs.filter(([f, t]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== t).map(([f]) => path.relative(repo, f));
  console.log(stale.length ? `stale: ${stale.join(', ')} (run node diff/core/webgl/tools/gen_mock.mjs)` : 'mock_gl.cjs and webgl_mock_gl_test.mbt are up to date');
  process.exit(stale.length ? 1 : 0);
}
for (const [f, t] of outputs) fs.writeFileSync(f, t);
console.log('mock written');
