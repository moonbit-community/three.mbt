// Embeds harness/mock_audio_body.js in <repo>/src/audio/audio_mock_test.mbt so the MoonBit
// tests run the same mock as the upstream scenarios.
// Usage: node tools/gen_mock.mjs [<three.mbt repo>]   (then `moonfmt -w` the output)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { REPO } from '../../../lib/env.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = process.argv[2] ?? REPO;
export const mockBody = () => fs.readFileSync(path.join(here, '../harness/mock_audio_body.js'), 'utf8');
export const embedded = (body) => ['() => {', ...body.trimEnd().split('\n'), 'return { createMockAudio };', '}'];

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const lines = embedded(mockBody()).map((l) => '  #|' + l);
  const out = [
    '// Generated by the audio_diff harness (tools/gen_mock.mjs) from harness/mock_audio_body.js:',
    '// the recording mock Web Audio context the tests use. Do not edit by hand.',
    '',
    '///|',
    'extern "js" fn ffi_mock_audio_module() -> @core.JsValue =',
    ...lines,
    '',
  ].join('\n');
  const file = path.join(repo, 'src/audio/audio_mock_test.mbt');
  fs.writeFileSync(file, out);
  console.log('wrote', file);
}
