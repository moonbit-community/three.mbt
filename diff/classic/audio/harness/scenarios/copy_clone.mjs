import { setup } from '../common.mjs';
export async function run(env) {
  const { ctx, Audio, AudioListener, PositionalAudio, Object3D, finish, note } = await setup(env);
  const listener = new AudioListener();
  const sound = new Audio(listener);
  const buffer = ctx.__buffer(5);
  const f1 = ctx.createBiquadFilter();
  sound.setBuffer(buffer);
  sound.detune = 10;
  sound.loop = true;
  sound.loopStart = 0.5;
  sound.loopEnd = 2;
  sound.offset = 0.25;
  sound.duration = 3;
  sound.playbackRate = 1.25;
  sound.setFilters([f1]);
  sound.position.set(1, 2, 3);
  sound.name = 'snd';
  sound.add(new Object3D());
  const c = sound.clone();
  const fields = (label, a) => {
    for (const k of ['type', 'name', 'autoplay', 'detune', 'loop', 'loopStart', 'loopEnd', 'offset', 'duration', 'playbackRate', 'hasPlaybackControl', 'sourceType', 'isPlaying', 'filters']) note(label + '.' + k, a[k]);
    note(label + '.buffer', a.buffer);
    note(label + '.position.x', a.position.x);
    note(label + '.children', a.children.length);
  };
  fields('c', c);
  note('c.filters copied', c.filters !== sound.filters);
  note('c.listener', c.listener === listener);
  const pa = new PositionalAudio(listener);
  pa.setBuffer(buffer);
  pa.setRefDistance(5);
  const pc = pa.clone();
  note('pc.getRefDistance', pc.getRefDistance());
  note('pc.type', pc.type);
  note('pc.getOutput', pc.getOutput());
  const nodeAudio = new Audio(listener);
  nodeAudio.setNodeSource(ctx.createOscillator());
  const target = new Audio(listener);
  target.copy(nodeAudio);
  fields('target', target);
  target.copy(new Object3D());
  const lc = listener.clone();
  note('lc.type', lc.type);
  note('lc.timeDelta', lc.timeDelta);
  const c2 = sound.clone(false);
  note('c2.children', c2.children.length);
  return finish();
}
