import { setup } from '../common.mjs';
export async function run(env) {
  const { ctx, AudioListener, Object3D, finish, note } = await setup(env);
  const listener = new AudioListener();
  note('type', listener.type);
  note('timeDelta', listener.timeDelta);
  const camera = new Object3D();
  camera.add(listener);
  camera.position.set(1, 2, 3);
  camera.rotation.set(0.3, -0.7, 0.1);
  listener.position.set(0.5, 0, -0.25);
  ctx.__setTime(0.5);
  ctx.__setNow(16);
  camera.updateMatrixWorld();
  note('timeDelta', listener.timeDelta);
  ctx.__setTime(1.25);
  ctx.__setNow(48.5);
  listener.rotateY(0.4);
  listener.updateMatrixWorld(true);
  note('timeDelta', listener.timeDelta);
  note('getMasterVolume', listener.getMasterVolume());
  listener.setMasterVolume(0.3);
  note('getInput', listener.getInput());
  const f1 = ctx.createBiquadFilter();
  const f2 = ctx.createBiquadFilter();
  listener.setFilter(f1);
  listener.setFilter(f2);
  note('getFilter', listener.getFilter());
  listener.removeFilter();
  listener.removeFilter();
  note('getFilter', listener.getFilter());
  camera.updateMatrixWorld();
  note('timeDelta', listener.timeDelta);
  camera.scale.set(2, 0.5, -1);
  ctx.__setNow(1000.125);
  camera.updateMatrixWorld();
  note('timeDelta', listener.timeDelta);
  return finish();
}
