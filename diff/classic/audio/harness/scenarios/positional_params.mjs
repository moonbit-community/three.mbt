import { setup } from '../common.mjs';
export async function run(env) {
  const { ctx, AudioListener, PositionalAudio, Object3D, finish, note, noteState } = await setup(env);
  const listener = new AudioListener();
  const camera = new Object3D();
  camera.add(listener);
  camera.position.set(0, 1.5, 4);
  const pa = new PositionalAudio(listener);
  note('type', pa.type);
  note('getRefDistance', pa.getRefDistance());
  note('getRolloffFactor', pa.getRolloffFactor());
  note('getDistanceModel', pa.getDistanceModel());
  note('getMaxDistance', pa.getMaxDistance());
  note('getOutput', pa.getOutput());
  pa.setRefDistance(2.5).setRolloffFactor(0.75).setDistanceModel('linear').setMaxDistance(80).setDirectionalCone(90, 220, 0.2);
  note('getRefDistance', pa.getRefDistance());
  note('getRolloffFactor', pa.getRolloffFactor());
  note('getDistanceModel', pa.getDistanceModel());
  note('getMaxDistance', pa.getMaxDistance());
  const scene = new Object3D();
  scene.add(camera);
  scene.add(pa);
  pa.position.set(3, 1, -2);
  pa.rotation.set(0.2, 1.1, -0.4);
  ctx.__setTime(0.5);
  ctx.__setNow(20);
  scene.updateMatrixWorld();
  pa.setBuffer(ctx.__buffer(3));
  pa.play();
  ctx.__setTime(0.75);
  ctx.__setNow(36);
  scene.updateMatrixWorld();
  const f1 = ctx.createBiquadFilter();
  pa.setFilters([f1]);
  pa.pause();
  noteState('pa', pa);
  scene.updateMatrixWorld();
  pa.disconnect();
  pa.disconnect();
  const pa2 = new PositionalAudio(listener);
  pa2.setNodeSource(ctx.createOscillator());
  scene.add(pa2);
  pa2.position.set(-1, -2, -3);
  ctx.__setTime(1);
  ctx.__setNow(52.5);
  scene.updateMatrixWorld();
  pa2.updateMatrixWorld(true);
  return finish();
}
