import { setup } from '../common.mjs';
export async function run(env) {
  const { ctx, Audio, AudioListener, finish, note, noteState } = await setup(env);
  const listener = new AudioListener();
  const sound = new Audio(listener);
  note('type', sound.type);
  note('sourceType', sound.sourceType);
  const buffer = ctx.__buffer(4);
  sound.setBuffer(buffer);
  note('sourceType', sound.sourceType);
  sound.setLoopStart(0.5).setLoopEnd(3.5);
  ctx.__setTime(1);
  sound.play(0.25);
  noteState('a', sound);
  sound.play();
  ctx.__setTime(2);
  sound.setDetune(100);
  sound.setPlaybackRate(1.5);
  sound.setLoop(true);
  note('getLoop', sound.getLoop());
  ctx.__setTime(3.5);
  sound.pause();
  noteState('b', sound);
  sound.offset = 0.125;
  sound.duration = 2;
  ctx.__setTime(4);
  sound.play();
  ctx.__setTime(6.75);
  sound.pause();
  noteState('c', sound);
  sound.setLoop(false);
  sound.play();
  ctx.__end(sound.source);
  noteState('d', sound);
  sound.stop(0.5);
  noteState('e', sound);
  sound.setVolume(0.25);
  note('getVolume', sound.getVolume());
  note('getDetune', sound.getDetune());
  note('getPlaybackRate', sound.getPlaybackRate());
  sound.setDetune(-50);
  sound.duration = 0;
  sound.setLoop(true);
  ctx.__setTime(7);
  sound.play();
  ctx.__setTime(12.5);
  sound.pause();
  noteState('f', sound);
  sound.pause();
  ctx.__setTime(13);
  sound.play(1);
  sound.pause();
  noteState('g', sound);
  sound.stop();
  noteState('h', sound);
  sound.duration = NaN;
  ctx.__setTime(20);
  sound.play();
  ctx.__setTime(26);
  sound.pause();
  noteState('i', sound);
  const auto = new Audio(listener);
  auto.autoplay = true;
  auto.setBuffer(buffer);
  noteState('auto', auto);
  const fresh = new Audio(listener);
  fresh.stop();
  noteState('fresh', fresh);
  return finish();
}
